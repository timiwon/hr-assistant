create table public.candidate_job_results (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  status character varying not null,
  note text null,
  candidate_id bigint not null,
  job_id bigint not null,
  constraint candidate_job_results_pkey primary key (id),
  constraint candidate_job_results_candidate_id_fkey foreign KEY (candidate_id) references candidates (id) on delete CASCADE,
  constraint candidate_job_results_job_id_fkey foreign KEY (job_id) references jobs (id) on delete CASCADE
) TABLESPACE pg_default;